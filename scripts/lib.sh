MARKER="generated by agent-project-framework"

say()  { printf '%s\n' "$*"; }
warn() { printf 'warn: %s\n' "$*" >&2; }
err()  { printf 'error: %s\n' "$*" >&2; }
die()  { err "$*"; exit 1; }

# Estimate tokens for a text file (chars / 4, rounded up).
est_tokens() {
  local file="$1" chars
  [ -f "$file" ] || { printf '0'; return; }
  chars=$(wc -c < "$file" | tr -d '[:space:]')
  awk -v c="$chars" 'BEGIN { printf "%d", (c + 3) / 4 }'
}

line_count() {
  local file="$1"
  [ -f "$file" ] || { printf '0'; return; }
  awk 'END { print NR }' "$file"
}

# Print the description from a SKILL.md YAML frontmatter.
skill_description() {
  local file="$1"
  awk '
    BEGIN { fm = 0; found = 0 }
    /^---[[:space:]]*$/ {
      if (fm == 0) { fm = 1; next }
      exit
    }
    fm && /^description:[[:space:]]*/ {
      sub(/^description:[[:space:]]*/, "")
      gsub(/^["'\'']|["'\'']$/, "")
      print
      exit
    }
  ' "$file"
}

# Print a skill body without its YAML frontmatter.
skill_body() {
  local file="$1"
  awk '
    BEGIN { fm = 0; body = 0 }
    /^---[[:space:]]*$/ {
      if (fm == 0) { fm = 1; next }
      if (fm == 1) { fm = 2; body = 1; next }
    }
    body { print }
  ' "$file"
}

# True when a file is safe to overwrite (missing, generated, or --force).
can_write() {
  local dest="$1"
  [ -e "$dest" ] || return 0
  if grep -q "$MARKER" "$dest" 2>/dev/null; then
    return 0
  fi
  if [ "${FORCE:-0}" = "1" ]; then
    return 0
  fi
  warn "skip $dest (exists and is not generated; use --force to overwrite)"
  return 1
}

# Create a relative symlink, or copy when COPY=1.
link_path() {
  local src="$1" dest="$2" rel="$3"

  mkdir -p "$(dirname "$dest")"

  if [ -L "$dest" ]; then
    if [ "${COPY:-0}" != "1" ] && [ "$(readlink "$dest")" = "$rel" ]; then
      return 0
    fi
    if [ "${COPY:-0}" = "1" ] || [ "${FORCE:-0}" = "1" ]; then
      rm -f "$dest"
    else
      warn "skip $dest (symlink to $(readlink "$dest"))"
      return 0
    fi
  elif [ -e "$dest" ]; then
    if [ "${COPY:-0}" = "1" ]; then
      if [ -d "$dest" ]; then
        cp -R "$src/." "$dest/"
      else
        cp "$src" "$dest"
      fi
      return 0
    fi
    if [ "${FORCE:-0}" = "1" ]; then
      rm -rf "$dest"
    else
      warn "skip $dest (exists; use --force to replace)"
      return 0
    fi
  fi

  if [ "${COPY:-0}" = "1" ]; then
    cp -R "$src" "$dest"
  else
    ln -s "$rel" "$dest"
  fi
}

slugify() {
  printf '%s' "$1" \
    | tr '[:upper:]' '[:lower:]' \
    | sed -E 's/[^a-z0-9]+/-/g; s/^-+//; s/-+$//' \
    | cut -c1-60
}

# Next zero-padded number from files matching a glob prefix.
next_number() {
  local dir="$1" prefix="$2" width="$3" max=0 n
  if [ -d "$dir" ]; then
    while IFS= read -r f; do
      n=$(basename "$f" | sed -E "s/^${prefix}([0-9]+).*/\\1/")
      case "$n" in
        ''|*[!0-9]*) continue ;;
      esac
      # strip leading zeros for arithmetic
      n=$((10#$n))
      [ "$n" -gt "$max" ] && max=$n
    done < <(find "$dir" -maxdepth 1 -type f -name "${prefix}*" 2>/dev/null)
  fi
  printf "%0${width}d" $((max + 1))
}

# Replace a literal token in a file (portable, handles & and /).
replace_token() {
  local file="$1" token="$2" value="$3"
  [ -f "$file" ] || return 0
  TOKEN="$token" VALUE="$value" perl -pi -e 's/\Q$ENV{TOKEN}\E/$ENV{VALUE}/g' "$file"
}
